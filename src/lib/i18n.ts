export type Key = keyof typeof en;
export type Vars = Record<string, string | number>;
export type T = (key: Key, vars?: Vars) => string;

export function translate(key: Key, vars?: Vars): string {
  let s: string = en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const t: T = (key, vars) => translate(key, vars);

/** The game is English only; `t` keeps one identity, so it is safe in hook dependency lists. */
export function useT(): T {
  return t;
}

/** Translated text for a server/app error; falls back to the raw message for unknown codes. */
export function errorText(t: T, e: AppError): string {
  const key = `err_${e.code}`;
  if (key in en) return t(key as Key);
  return e.message || t('err_unknown');
}
